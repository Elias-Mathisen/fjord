# Downloads Fjord's new-tab photos (listed in tools\photos.txt) into src\fjord\photos\ and writes photos.js (credits).
# Photos are from Unsplash under the Unsplash License (free to use, credit appreciated).
# Bundled so the new tab never contacts a server. Run only when the photo list changes.
# The first photo comes with Fjord as photo-001.jpg; the rest are named after their Unsplash image (u-<id>.jpg), so
# installed copies that downloaded them before keep the right photo with the right credit when the list changes.
param([int]$Width = 3840, [int]$Quality = 90)  # 4K wide at high quality, sharp on big and high-DPI screens
$ErrorActionPreference = 'Stop'
$ProgressPreference = 'SilentlyContinue'
Add-Type -AssemblyName System.Drawing
$out = Join-Path $PSScriptRoot '..\src\fjord\photos'
Remove-Item $out -Recurse -Force -ErrorAction SilentlyContinue
New-Item -ItemType Directory -Force $out | Out-Null

$photos = Get-Content (Join-Path $PSScriptRoot 'photos.txt') -Encoding UTF8 | Where-Object { $_ -and -not $_.StartsWith('#') }
$wc = New-Object Net.WebClient
$manifest = [ordered]@{ dark = @(); light = @() }
$i = 0
foreach ($line in $photos) {
    $img, $id, $by = $line -split '\|', 3
    $i++
    $file = if ($i -eq 1) { 'photo-001.jpg' } else { "u-$img.jpg" }
    $src = "https://images.unsplash.com/photo-$img`?w=$Width&q=$Quality&fm=jpg&fit=max"
    $wc.DownloadFile($src, "$out\$file")
    # Dark or light by average brightness, so the new tab can match the theme
    $bmp = [Drawing.Image]::FromFile("$out\$file")
    if ($bmp.Width -lt 2560) { Write-Warning "$file is only $($bmp.Width) px wide" }
    $small = New-Object Drawing.Bitmap $bmp, 24, 16
    $bmp.Dispose()
    $sum = 0; for ($x = 0; $x -lt 24; $x++) { for ($y = 0; $y -lt 16; $y++) { $sum += $small.GetPixel($x, $y).GetBrightness() } }
    $small.Dispose()
    $mode = if ($sum / 384 -lt 0.45) { 'dark' } else { 'light' }
    # src: where the installer downloads it from, so the installer itself stays small
    $manifest[$mode] += [ordered]@{ file = "photos/$file"; by = $by; page = "https://unsplash.com/photos/$id"; src = $src }
}
$json = $manifest | ConvertTo-Json -Depth 4
[IO.File]::WriteAllText((Join-Path $PSScriptRoot '..\src\fjord\photos.js'),
    "// Generated by tools/get-photos.ps1. New-tab photos from Unsplash (Unsplash License).`nconst PHOTOS = $json;`n", (New-Object Text.UTF8Encoding $false))
Get-ChildItem $out | Measure-Object Length -Sum | ForEach-Object { "{0} photos ({1} dark, {2} light), {3:N0} MB" -f $_.Count, $manifest.dark.Count, $manifest.light.Count, ($_.Sum / 1MB) }
